// Writes, from shared/courses.csv, two files that the image build cannot make by itself:
//   public/sitemap.xml   for search engines: the site's main pages and one page per course.
//   scripts/courses.ts   each course's number and name, for the build (vite.config.ts), which
//                        writes every course page's HTML with its own title and description.
// Run it again whenever shared/courses.csv changes, and commit both results:
//   npm --prefix public-frontend run sitemap
// (The image is built from public-frontend/ alone, so it cannot read shared/ at build time.)

import { readFileSync, writeFileSync } from "node:fs";

const SITE = "https://openuvoice.com";

const PAGES = [
  "/",
  "/courses",
  "/chat",
  "/chat/general",
  "/announcements",
  "/inquiry",
  "/about",
  "/privacy",
];

// Course 0 is the general chat, which has its own address (/chat/general).
const GENERAL_CHAT_ID = "0";

const csvFile = new URL("../../shared/courses.csv", import.meta.url);
const sitemapFile = new URL("../public/sitemap.xml", import.meta.url);
const coursesFile = new URL("./courses.ts", import.meta.url);

/** One CSV line into its fields. A field in double quotes may hold commas and "" (one quote). */
function parseCsvLine(line) {
  const fields = [];
  let field = "";
  let quoted = false;
  for (let i = 0; i < line.length; i++) {
    const ch = line[i];
    if (quoted) {
      if (ch === '"' && line[i + 1] === '"') {
        field += '"';
        i++;
      } else if (ch === '"') {
        quoted = false;
      } else {
        field += ch;
      }
    } else if (ch === '"') {
      quoted = true;
    } else if (ch === ",") {
      fields.push(field);
      field = "";
    } else {
      field += ch;
    }
  }
  fields.push(field);
  return fields;
}

const courses = readFileSync(csvFile, "utf8")
  .split(/\r?\n/)
  .slice(1)
  .filter((line) => line.trim() !== "")
  .map(parseCsvLine)
  .map(([id = "", name = ""]) => ({ id: id.trim(), name: name.trim() }))
  .filter((course) => course.id !== GENERAL_CHAT_ID);

const bad = courses.find((course) => !/^\d+$/.test(course.id) || course.name === "");
if (courses.length === 0 || bad !== undefined) {
  throw new Error(`unexpected course in shared/courses.csv (${bad ? bad.id : "none found"})`);
}

const paths = [...PAGES, ...courses.map((course) => `/courses/${course.id}`)];

const xml = [
  '<?xml version="1.0" encoding="UTF-8"?>',
  "<!-- Generated by scripts/sitemap.mjs from shared/courses.csv. Do not edit by hand. -->",
  '<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9">',
  ...paths.map((path) => `  <url><loc>${SITE}${path}</loc></url>`),
  "</urlset>",
  "",
].join("\n");

// JSON.stringify writes each name as a valid string, whatever quotes or backslashes it holds.
const ts = [
  "// Generated by scripts/sitemap.mjs from shared/courses.csv. Do not edit by hand.",
  "",
  "export const COURSES: readonly { id: number; name: string }[] = [",
  ...courses.map((course) => `  { id: ${course.id}, name: ${JSON.stringify(course.name)} },`),
  "];",
  "",
].join("\n");

writeFileSync(sitemapFile, xml);
writeFileSync(coursesFile, ts);
console.log(`sitemap.xml: ${paths.length} pages, courses.ts: ${courses.length} courses`);
