// Writes public/sitemap.xml for search engines: the site's main pages and one page per course.
// Run it again whenever shared/courses.csv changes, and commit the result:
//   npm --prefix public-frontend run sitemap
// (The image is built from public-frontend/ alone, so it cannot read shared/ at build time.)

import { readFileSync, writeFileSync } from "node:fs";

const SITE = "https://openuvoice.com";

const PAGES = [
  "/",
  "/courses",
  "/chat",
  "/chat/general",
  "/announcements",
  "/inquiry",
  "/about",
  "/privacy",
];

// Course 0 is the general chat, which has its own address (/chat/general).
const GENERAL_CHAT_ID = "0";

const csvFile = new URL("../../shared/courses.csv", import.meta.url);
const sitemapFile = new URL("../public/sitemap.xml", import.meta.url);

// Only the first column (course_id) is needed; it is a plain number, never quoted.
const ids = readFileSync(csvFile, "utf8")
  .split(/\r?\n/)
  .slice(1)
  .map((line) => line.split(",", 1)[0].trim())
  .filter((id) => id !== "" && id !== GENERAL_CHAT_ID);

const bad = ids.find((id) => !/^\d+$/.test(id));
if (ids.length === 0 || bad !== undefined) {
  throw new Error(`unexpected course ids in shared/courses.csv (${bad ?? "none found"})`);
}

const paths = [...PAGES, ...ids.map((id) => `/courses/${id}`)];

const xml = [
  '<?xml version="1.0" encoding="UTF-8"?>',
  "<!-- Generated by scripts/sitemap.mjs from shared/courses.csv. Do not edit by hand. -->",
  '<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9">',
  ...paths.map((path) => `  <url><loc>${SITE}${path}</loc></url>`),
  "</urlset>",
  "",
].join("\n");

writeFileSync(sitemapFile, xml);
console.log(`sitemap.xml: ${paths.length} pages (${ids.length} courses)`);